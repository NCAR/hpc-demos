#!/usr/bin/env bash
#
# make_climo.sh [-- qsub args]
#
# Builds the 1991-2020 ERA5 temperature climatology that
# calc_anomaly_numba_climo.py reads: one launch_cf step per calendar day,
# 366 in all (29 February from the leap years only), each running
# make_climo_day.py on that day's 30 files and writing
# climo/T_1991-2020_MMDD.h5 (154 MB each, 56 GB in all).
#
# The steps are bound to NUMA domains with numactl and run in synchronized
# waves: THREADS threads each, so 128 / THREADS at once per node.
#
# Environment:
#   NODES=4  THREADS=4  QUEUE=main  WALLTIME=0:40:00
#   DAYS     only these days, e.g. DAYS="0101 0229" (default: all 366)
#   DRYRUN=1 write everything, but don't submit
#
# Days whose file already exists are left out, so after a failure, running
# make_climo.sh again submits only what is missing.

set -euo pipefail
[ $# -gt 0 ] && [ "$1" = "--" ] && shift
qsub_args=("$@")

NODES="${NODES:-4}"
THREADS="${THREADS:-4}"
NUMA_PER_NODE=8
export PATH=/glade/derecho/scratch/kedziora/pbstools/bin:$PATH

mkdir -p climo cmdfiles pbs logs
days="${DAYS:-$(python3 -c "
import datetime as d
t = d.date(2020, 1, 1)                      # a leap year: all 366 days
while t.year == 2020:
    print(t.strftime('%m%d')); t += d.timedelta(1)")}"

cmdfile=cmdfiles/cmdfile.climo
i=0
{
    echo "# Generated by make_climo.sh"
    for mmdd in ${days}; do
        [ -f "climo/T_1991-2020_${mmdd}.h5" ] && continue
        domain=$(( i % NUMA_PER_NODE ))
        echo "OMP_NUM_THREADS=${THREADS} numactl --cpunodebind=${domain} --membind=${domain} ./run_climo_day.sh ${mmdd}"
        i=$(( i + 1 ))
    done
} > "${cmdfile}"
[ "${i}" -gt 0 ] || { echo "all days are done"; exit 0; }
[ "${NODES}" -gt "${i}" ] && NODES="${i}"

echo "== ${i} days, ${THREADS} threads per step, ${NODES} node(s)"
launch_cf -q "${QUEUE:-main}" -l walltime="${WALLTIME:-0:40:00}" -A "${PBS_ACCOUNT}" \
    -N climo --nodes "${NODES}" --nthreads "${THREADS}" --sync-waves \
    --script pbs/launch_cf.climo.pbs ${DRYRUN:+--dryrun} "${qsub_args[@]}" \
    "${cmdfile}" |& tee logs/launch_cf.climo.log
