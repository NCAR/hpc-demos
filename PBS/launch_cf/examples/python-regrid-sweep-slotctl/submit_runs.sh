#!/usr/bin/env bash
#
# submit_runs.sh <threads per step> <total steps> [waves per node]
#
# Writes an unbound and a bound launch_cf command file of <total steps> steps
# (ensemble members) of <threads per step> threads each, and submits each with
# launch_cf.  Every node is packed: it runs 128 / <threads> steps at once, 128
# threads in all, and starts a new step whenever one finishes.  Each node is
# given <waves per node> (default 1) times that many steps, and launch_cf
# makes a job array of as many nodes as the total needs:
#
#   steps at once  = 128 / threads
#   steps per node = waves per node * steps at once
#   nodes          = total steps / steps per node, rounded up
#
# e.g. "./submit_runs.sh 8 128 2": 16 steps at once, 32 per node in 2 waves,
# a job array of 4 nodes.
#
# Each run is named for its placement, threads, total steps and waves per
# node, e.g. unbound.t08.n128.w2:
#
#   cmdfiles/cmdfile.unbound.t08.n128.w2     the command file
#   pbs/launch_cf.unbound.t08.n128.w2.pbs    the job script launch_cf writes
#   logs/launch_cf.unbound.t08.n128.w2.log   launch_cf's output, with the job id
#   rs-u-t08-n128-w2.o<job id>.<index>       PBS output, one per node
#   stdout-<job id>/                         the steps' output
#
# Summarize finished runs with ./summarize.py.
#
# Environment:
#   PLACEMENTS="unbound bound"  which runs to submit
#   QUEUE                       default: develop for 1 or 2 nodes, else main
#                               (develop runs at most 256 cores, 2 nodes, of a
#                               user's jobs at once, and arrays of at most 4)
#   WALLTIME=0:10:00            per node
#   ITERS=40                    iterations per step (calc_anomaly_numba.py --iters);
#                               more makes computing outweigh startup
#   DRYRUN=1                    write everything, but don't submit

set -euo pipefail

usage() { sed -n '3,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; }

[ $# -eq 2 ] || [ $# -eq 3 ] || { usage; exit 1; }
threads="$1"
nsteps="$2"
waves="${3:-1}"

CORES_PER_NODE=128

case "${threads}" in
    1|2|4|8|16) ;;
    *) echo "ERROR: threads per step must be 1, 2, 4, 8 or 16 (divide a 16-core NUMA domain)"; exit 1 ;;
esac
for v in "${nsteps}" "${waves}"; do
    [[ "${v}" =~ ^[1-9][0-9]*$ ]] || { echo "ERROR: steps and waves must be positive whole numbers"; exit 1; }
done

steps_at_once=$(( CORES_PER_NODE / threads ))
steps_per_node=$(( waves * steps_at_once ))
nodes=$(( (nsteps + steps_per_node - 1) / steps_per_node ))
if [ ${nsteps} -lt ${steps_per_node} ]; then
    echo "ERROR: ${nsteps} steps don't fill ${waves} wave(s) of ${steps_at_once} on even one node"
    exit 1
fi
if [ $(( nsteps % steps_per_node )) -ne 0 ]; then
    echo "NOTE: the last node gets $(( nsteps % steps_per_node )) steps, not ${steps_per_node}"
fi

queue="${QUEUE:-}"
if [ -z "${queue}" ]; then
    if [ ${nodes} -le 2 ]; then queue=develop; else queue=main; fi
fi

# launch_cf from the branch that runs steps in waves (launch_cf-multiple-waves)
export PATH=/glade/derecho/scratch/kedziora/pbstools/bin:$PATH

mkdir -p cmdfiles pbs logs
for placement in ${PLACEMENTS:-unbound bound}; do
    tag=$(printf "%s.t%02d.n%03d.w%d" "${placement}" "${threads}" "${nsteps}" "${waves}")
    name=$(printf "rs-%s-t%02d-n%03d-w%d" "${placement:0:1}" "${threads}" "${nsteps}" "${waves}")
    cmdfile="cmdfiles/cmdfile.${tag}"

    {
        echo "# ${nsteps} steps of ${threads} threads, ${placement}: ${steps_at_once} at once per node,"
        echo "# ${steps_per_node} per node in ${waves} wave(s), on ${nodes} node(s)"
        echo "# Generated by submit_runs.sh ${threads} ${nsteps} ${waves}${ITERS:+ with ITERS=${ITERS}}"
        for (( member = 1; member <= nsteps; member++ )); do
            echo "OMP_NUM_THREADS=${threads} STEPS_AT_ONCE=${steps_at_once} ./run_step.sh ${placement} ${member}${ITERS:+ --iters ${ITERS}}"
        done
    } > "${cmdfile}"

    echo "== ${tag}: ${nsteps} steps, ${steps_at_once} at once, ${steps_per_node} per node" \
         "(${waves} wave(s)), ${nodes} node(s), queue ${queue}"
    launch_cf -q "${queue}" -l walltime="${WALLTIME:-0:10:00}" -A "${PBS_ACCOUNT}" \
        -N "${name}" --steps-per-node ${steps_per_node} --nthreads ${threads} \
        --script "pbs/launch_cf.${tag}.pbs" ${DRYRUN:+--dryrun} \
        "${cmdfile}" |& tee "logs/launch_cf.${tag}.log"
done
