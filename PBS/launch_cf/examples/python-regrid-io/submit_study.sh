#!/usr/bin/env bash
#
# submit_study.sh <io|pario|keep> <bound|unbound> <threads> <nodes> <waves> <first file> [-- qsub args]
#
# Runs ERA5 files from era5_t_files.txt, starting at line <first file>
# (counting from 0), one file per launch_cf step of <threads> threads, with
#
#   io     calc_anomaly_numba_io.py     h5py, decompression on one thread
#   pario  calc_anomaly_numba_pario.py  decompression on <threads> I/O threads
#   keep   calc_anomaly_numba_pario.py --keep: each chunk decompressed once,
#          about 3.7 GB more memory per step
#
# Both make two passes over their file (daily mean, then anomaly).
#
# Every node is packed: it runs 128 / threads steps at once, in <waves>
# waves, so the run uses <nodes> x <waves> x 128 / threads files:
#
#   unbound  Linux places each step's threads and memory.  launch_cf starts
#            a new step as soon as any running step finishes.
#   bound    each step runs under numactl in NUMA domain (line - 1) mod 8,
#            and launch_cf --sync-waves starts a node's next wave only once
#            every step of the one before has finished.
#
# Each run is named <script>.<placement>.tTT.nNN.wW.fFFFFF:
#
#   cmdfiles/cmdfile.<run>       the command file
#   pbs/launch_cf.<run>.pbs      the job script launch_cf writes
#   logs/launch_cf.<run>.log     launch_cf's output, with the job id
#   <name>.o<job id>[.<index>]   PBS output, one per node
#   stdout-<job id>/             the steps' output
#
# Anything after "--" goes to qsub, e.g. "-- -W depend=afterany:1234".
# Summarize finished runs with ./summarize_study.py.
#
# Environment:
#   QUEUE      default: develop for 1 or 2 nodes, else main
#   WALLTIME=0:20:00
#   DRYRUN=1   write everything, but don't submit

set -euo pipefail

usage() { sed -n '3,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; }

[ $# -ge 6 ] || { usage; exit 1; }
script="$1"; placement="$2"; threads="$3"; nodes="$4"; waves="$5"; first="$6"; shift 6
[ $# -gt 0 ] && [ "$1" = "--" ] && shift
qsub_args=("$@")

CORES_PER_NODE=128
NUMA_PER_NODE=8

case "${script}" in io|pario|keep) ;; *) echo "ERROR: script must be io, pario or keep"; exit 1 ;; esac
case "${placement}" in bound|unbound) ;; *) echo "ERROR: placement must be bound or unbound"; exit 1 ;; esac
case "${threads}" in
    1|2|4|8|16) ;;
    *) echo "ERROR: threads per step must be 1, 2, 4, 8 or 16 (divide a 16-core NUMA domain)"; exit 1 ;;
esac
for v in "${nodes}" "${waves}"; do
    [[ "${v}" =~ ^[1-9][0-9]*$ ]] || { echo "ERROR: nodes and waves must be positive whole numbers"; exit 1; }
done
[ -f era5_t_files.txt ] || { echo "ERROR: no era5_t_files.txt; run ./make_filelist.sh"; exit 1; }

at_once=$(( CORES_PER_NODE / threads ))
steps_per_node=$(( waves * at_once ))
nfiles=$(( nodes * steps_per_node ))
total=$(wc -l < era5_t_files.txt)
[ $(( first + nfiles )) -le "${total}" ] || { echo "ERROR: needs files ${first}..$(( first + nfiles - 1 )), only ${total} listed"; exit 1; }

queue="${QUEUE:-}"
if [ -z "${queue}" ]; then
    # develop runs at most 256 cores (2 nodes) of a user's jobs at once
    if [ "${nodes}" -le 2 ]; then queue=develop; else queue=main; fi
fi

export PATH=/glade/derecho/scratch/kedziora/pbstools/bin:$PATH

mkdir -p cmdfiles pbs logs
tag=$(printf "%s.%s.t%02d.n%02d.w%d.f%05d" "${script}" "${placement}" "${threads}" "${nodes}" "${waves}" "${first}")
name=$(printf "%s-%s-t%02d-n%d-w%d" "${script}" "${placement:0:1}" "${threads}" "${nodes}" "${waves}")
cmdfile="cmdfiles/cmdfile.${tag}"

{
    echo "# Generated by submit_study.sh ${script} ${placement} ${threads} ${nodes} ${waves} ${first}"
    sed -n "$(( first + 1 )),$(( first + nfiles ))p" era5_t_files.txt | {
        i=0
        while read -r f; do
            run="./run_io_step.sh ${script} $(( i + 1 )) ${f}"
            if [ "${placement}" = bound ]; then
                domain=$(( i % NUMA_PER_NODE ))
                echo "OMP_NUM_THREADS=${threads} numactl --cpunodebind=${domain} --membind=${domain} ${run}"
            else
                echo "OMP_NUM_THREADS=${threads} ${run}"
            fi
            i=$(( i + 1 ))
        done
    }
} > "${cmdfile}"

sync=()
[ "${placement}" = bound ] && sync=(--sync-waves)

echo "== ${tag}: ${nfiles} files, ${at_once} steps at once, ${steps_per_node} per node" \
     "(${waves} wave(s)${sync:+, synchronized}), ${nodes} node(s), queue ${queue}"
launch_cf -q "${queue}" -l walltime="${WALLTIME:-0:20:00}" -A "${PBS_ACCOUNT}" \
    -N "${name}" --steps-per-node "${steps_per_node}" --nthreads "${threads}" "${sync[@]}" \
    --script "pbs/launch_cf.${tag}.pbs" ${DRYRUN:+--dryrun} "${qsub_args[@]}" \
    "${cmdfile}" |& tee "logs/launch_cf.${tag}.log"
