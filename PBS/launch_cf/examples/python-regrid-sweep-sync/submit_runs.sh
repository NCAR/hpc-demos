#!/usr/bin/env bash
#
# submit_runs.sh <threads per step> <total steps> [waves per node]
#
# Writes two launch_cf command files of <total steps> steps (ensemble members)
# of <threads per step> threads each, one unbound and one bound, and submits
# each with launch_cf.  Every node is packed with 128 threads: it runs
# 128 / <threads> steps at once.  Each node is given <waves per node>
# (default 1) times that many steps, and launch_cf makes a job array of as
# many nodes as the total needs:
#
#   steps at once  = 128 / threads
#   steps per node = waves per node * steps at once   (launch_cf --steps-per-node)
#   nodes          = total steps / steps per node     (the job array)
#
#   unbound  Linux places each step's threads and memory.  launch_cf starts
#            a new step as soon as any running step finishes.
#   bound    each line runs its step under numactl in NUMA domain
#            (line - 1) mod 8, and launch_cf --sync-waves starts a node's next
#            wave only once every step of the one before has finished.  So the
#            steps running together are always one wave's lines, spread evenly
#            over the 8 domains.
#
# e.g. "./submit_runs.sh 8 128 2": 16 steps at once, 32 per node in 2 waves,
# a job array of 4 nodes.
#
# Each run is named for its placement, threads, total steps and waves per
# node, e.g. bound.t08.n128.w2:
#
#   cmdfiles/cmdfile.bound.t08.n128.w2     the command file
#   pbs/launch_cf.bound.t08.n128.w2.pbs    the job script launch_cf writes
#   logs/launch_cf.bound.t08.n128.w2.log   launch_cf's output, with the job id
#   rs-b-t08-n128-w2.o<job id>.<index>     PBS output, one per node
#   stdout-<job id>/                       the steps' output
#
# Summarize finished runs with ./summarize.py.
#
# Environment:
#   PLACEMENTS="unbound bound"  which runs to submit
#   QUEUE                       default: develop for 1 or 2 nodes, else main
#   WALLTIME=0:10:00            per node
#   ITERS                       iterations per step (calc_anomaly_numba.py --iters,
#                               default 40); 400 makes computing outweigh startup
#   DRYRUN=1                    write everything, but don't submit

set -euo pipefail

usage() { sed -n '3,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; }

[ $# -eq 2 ] || [ $# -eq 3 ] || { usage; exit 1; }
threads="$1"
nsteps="$2"
waves="${3:-1}"

CORES_PER_NODE=128
NUMA_PER_NODE=8

case "${threads}" in
    1|2|4|8|16) ;;
    *) echo "ERROR: threads per step must be 1, 2, 4, 8 or 16 (divide a 16-core NUMA domain)"; exit 1 ;;
esac
for v in "${nsteps}" "${waves}"; do
    [[ "${v}" =~ ^[1-9][0-9]*$ ]] || { echo "ERROR: steps and waves must be positive whole numbers"; exit 1; }
done

steps_at_once=$(( CORES_PER_NODE / threads ))
steps_per_node=$(( waves * steps_at_once ))
nodes=$(( (nsteps + steps_per_node - 1) / steps_per_node ))
if [ $(( nsteps % steps_per_node )) -ne 0 ]; then
    echo "ERROR: ${nsteps} steps don't make whole nodes of ${steps_per_node} (${waves} wave(s) of ${steps_at_once})"
    exit 1
fi

queue="${QUEUE:-}"
if [ -z "${queue}" ]; then
    # develop runs at most 256 cores (2 nodes) of a user's jobs at once
    if [ ${nodes} -le 2 ]; then queue=develop; else queue=main; fi
fi

# launch_cf from the branch that runs steps in waves (launch_cf-multiple-waves)
export PATH=/glade/derecho/scratch/kedziora/pbstools/bin:$PATH

mkdir -p cmdfiles pbs logs
for placement in ${PLACEMENTS:-unbound bound}; do
    tag=$(printf "%s.t%02d.n%03d.w%d" "${placement}" "${threads}" "${nsteps}" "${waves}")
    name=$(printf "rs-%s-t%02d-n%03d-w%d" "${placement:0:1}" "${threads}" "${nsteps}" "${waves}")
    cmdfile="cmdfiles/cmdfile.${tag}"

    sync=()
    {
        echo "# Generated by submit_runs.sh ${threads} ${nsteps} ${waves}${ITERS:+ with ITERS=${ITERS}}"
        for (( i = 0; i < nsteps; i++ )); do
            member=$(( i + 1 ))
            case "${placement}" in
                unbound)
                    echo "OMP_NUM_THREADS=${threads} ./run_step.sh ${member}${ITERS:+ --iters ${ITERS}}" ;;
                bound)
                    domain=$(( i % NUMA_PER_NODE ))
                    echo "OMP_NUM_THREADS=${threads} numactl --cpunodebind=${domain} --membind=${domain} ./run_step.sh ${member}${ITERS:+ --iters ${ITERS}}" ;;
                *)
                    echo "ERROR: placement must be unbound or bound, not '${placement}'" >&2; exit 1 ;;
            esac
        done
    } > "${cmdfile}"
    [ "${placement}" = bound ] && sync=(--sync-waves)

    echo "== ${tag}: ${nsteps} steps, ${steps_at_once} at once, ${steps_per_node} per node" \
         "(${waves} wave(s)${sync:+, synchronized}), ${nodes} node(s), queue ${queue}"
    launch_cf -q "${queue}" -l walltime="${WALLTIME:-0:10:00}" -A "${PBS_ACCOUNT}" \
        -N "${name}" --steps-per-node ${steps_per_node} --nthreads ${threads} "${sync[@]}" \
        --script "pbs/launch_cf.${tag}.pbs" ${DRYRUN:+--dryrun} \
        "${cmdfile}" |& tee "logs/launch_cf.${tag}.log"
done
