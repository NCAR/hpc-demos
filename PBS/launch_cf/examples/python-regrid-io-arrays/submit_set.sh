#!/usr/bin/env bash
#
# submit_set.sh <set> <first file> [nodes ...]
#
# Submits one "set": the same workflow, FILES ERA5 files through
# calc_anomaly_numba_pario.py (8 threads, bound, 16 steps at once per node),
# once for each node count, all at the same moment.  Each node count N is one
# launch_cf job array of N nodes; each node runs FILES / (16 N) synchronized
# waves.  So the work is the same in every run of the set, and only its shape
# changes: wide and short (many nodes, 1 wave) to narrow and long (1 node,
# many waves).
#
# Default node counts: 64 32 16 8 4 2 1, with FILES=1024.  Every run reads its
# own FILES consecutive files, starting at <first file>, so a set uses
# (number of runs) x FILES files.  The runs are submitted in a random order,
# so no shape is always first in line.
#
# Each run asks for walltime  300 s + 20 s per wave, rounded up to 5 minutes:
# a wave takes about 11 s (python-regrid-climo/DETAILS.md), so this is what a user who knew
# that would ask for.
#
# Writes, for each run,
#   cmdfiles/cmdfile.<set>.nNNN.wWW     the command file
#   pbs/launch_cf.<set>.nNNN.wWW.pbs    the job script launch_cf writes
#   logs/launch_cf.<set>.nNNN.wWW.log   launch_cf's output
# and appends  set,nodes,waves,walltime,first,jobid,submit_epoch  to runs.csv.
#
# Watch the set with ./sample_prio.sh <set>, summarize it with ./summarize.py.
#
# Environment:
#   FILES=1024    files per run (a multiple of 16 x the largest node count)
#   QUEUE=main    the same queue for every shape, so they compete alike
#   DRYRUN=1      write everything, submit nothing

set -euo pipefail
usage() { sed -n '3,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; }
[ $# -ge 2 ] || { usage; exit 1; }

set_name="$1"; first="$2"; shift 2
nodes_list=("$@")
[ ${#nodes_list[@]} -gt 0 ] || nodes_list=(64 32 16 8 4 2 1)

FILES="${FILES:-1024}"
QUEUE="${QUEUE:-main}"
THREADS=8
AT_ONCE=16
NUMA_PER_NODE=8

export PATH=/glade/derecho/scratch/kedziora/pbstools/bin:$PATH
mkdir -p cmdfiles pbs logs

total=$(wc -l < era5_t_files.txt)
need=$(( first + ${#nodes_list[@]} * FILES ))
[ "${need}" -le "${total}" ] || { echo "ERROR: needs files up to ${need}, only ${total} listed"; exit 1; }

# Write every command file first, so that the submissions themselves follow
# each other as closely as possible.
declare -A first_of
i=0
for n in "${nodes_list[@]}"; do
    [ $(( FILES % (n * AT_ONCE) )) -eq 0 ] || { echo "ERROR: ${FILES} files don't fill ${n} nodes x ${AT_ONCE}"; exit 1; }
    waves=$(( FILES / (n * AT_ONCE) ))
    f0=$(( first + i * FILES ))
    first_of[$n]=${f0}
    tag=$(printf "%s.n%03d.w%02d" "${set_name}" "${n}" "${waves}")
    {
        echo "# Generated by submit_set.sh ${set_name}: ${n} nodes x ${waves} waves, files ${f0}.."
        sed -n "$(( f0 + 1 )),$(( f0 + FILES ))p" era5_t_files.txt | {
            j=0
            while read -r f; do
                echo "OMP_NUM_THREADS=${THREADS} numactl --cpunodebind=$(( j % NUMA_PER_NODE )) --membind=$(( j % NUMA_PER_NODE )) ./run_io_step.sh pario $(( j + 1 )) ${f}"
                j=$(( j + 1 ))
            done
        }
    } > "cmdfiles/cmdfile.${tag}"
    i=$(( i + 1 ))
done

[ -f runs.csv ] || echo "set,nodes,waves,walltime,first,jobid,submit_epoch" > runs.csv

for n in $(printf "%s\n" "${nodes_list[@]}" | shuf); do
    waves=$(( FILES / (n * AT_ONCE) ))
    secs=$(( 300 + 20 * waves ))
    secs=$(( (secs + 299) / 300 * 300 ))
    walltime=$(printf "%d:%02d:00" $(( secs / 3600 )) $(( secs % 3600 / 60 )))
    tag=$(printf "%s.n%03d.w%02d" "${set_name}" "${n}" "${waves}")
    name=$(printf "ap-n%d-w%d" "${n}" "${waves}")
    echo "== ${tag}: ${n} node(s) x ${waves} wave(s), walltime ${walltime}, queue ${QUEUE}"
    launch_cf -q "${QUEUE}" -l walltime="${walltime}" -A "${PBS_ACCOUNT}" -N "${name}" \
        --steps-per-node $(( waves * AT_ONCE )) --nthreads "${THREADS}" --sync-waves \
        --script "pbs/launch_cf.${tag}.pbs" ${DRYRUN:+--dryrun} \
        "cmdfiles/cmdfile.${tag}" > "logs/launch_cf.${tag}.log" 2>&1
    now=$(date +%s)
    jobid=$(grep -E '^[0-9]+(\[\])?\.' "logs/launch_cf.${tag}.log" | tail -1 || true)
    echo "   ${jobid:-not submitted}"
    [ -n "${DRYRUN:-}" ] || echo "${set_name},${n},${waves},${walltime},${first_of[$n]},${jobid},${now}" >> runs.csv
done
